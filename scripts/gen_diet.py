def _fmt_list(items, numbered=False):
    if numbered:
        return "\n".join(f"{i}. {x}" for i, x in enumerate(items, 1))
    return "\n".join(f"- {x}" for x in items)


TEMPLATE = """# {name}

## 基本信息
- **功效**：{effect}
- **适合体质**：{body}
- **季节**：{season}

## 材料
{materials}

## 做法
{steps}

## 功效说明
{desc}

## 适宜人群
{suits}

## 禁忌与注意
{taboo}

> 以上为食疗养生参考，不替代药物。如有不适请及时就医。
"""


def main():
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "diet")
    os.makedirs(out_dir, exist_ok=True)
    for d in DIET:
        content = TEMPLATE.format(
            name=d["name"], effect=d["effect"], body="、".join(d["body"]), season=d["season"],
            materials=_fmt_list(d["materials"]),
            steps=_fmt_list(d["steps"], numbered=True),
            desc=_fmt_list(d["desc"]),
            suits=_fmt_list(d["suits"]),
            taboo=_fmt_list(d["taboo"]),
        )
        path = os.path.join(out_dir, f'{d["name"]}.md')
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
    print(f"已生成 {len(DIET)} 个食疗文档 → data/diet/")


if __name__ == "__main__":
    main()
