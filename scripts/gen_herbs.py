def _fmt_list(items, bullet="-", numbered=False):
    if numbered:
        return "\n".join(f"{i}. {x}" for i, x in enumerate(items, 1))
    return "\n".join(f"{bullet} {x}" for x in items)


TEMPLATE = """# {name}

## 基本信息
- **性味归经**：{nature}
- **分类**：{category}
- **常见用法**：{usage}

## 功效主治
主要功效包括：
{effects}

## 适用体质
{constitution}

## 禁忌与注意
{taboo}

## 常见搭配
{pair}

> 参考来源：《中国药典》2020年版、《中药学》规划教材。以上为养生科普，具体用药请遵医嘱。
"""


def main():
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "herbs")
    os.makedirs(out_dir, exist_ok=True)
    for h in HERBS:
        content = TEMPLATE.format(
            name=h["name"],
            nature=h["nature"],
            category=h["category"],
            usage=h["usage"],
            effects=_fmt_list(h["effects"], numbered=True),
            constitution=_fmt_list(h["constitution"]),
            taboo=_fmt_list(h["taboo"]),
            pair=_fmt_list(h["pair"]),
        )
        path = os.path.join(out_dir, f'{h["name"]}.md')
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
    print(f"已生成 {len(HERBS)} 味中药文档 → data/herbs/")


if __name__ == "__main__":
    main()
